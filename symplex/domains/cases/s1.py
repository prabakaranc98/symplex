"""S1 -- distrust on a network: contagion, homophily, or a shared shock.

Generator: many independent rating episodes on a small signed network. Every episode ends
up with negativity clustered on the graph, and each was produced by exactly one of three
mechanisms.

  contagion        ties form at random; a user's negativity rises after the users they are
                   tied to have rated negatively, with a lag.
  homophily        ties form preferentially between users of similar temperament; nobody
                   transmits anything. Clustering is a property of who connected to whom.
  exogenous_shock  ties form at random; one global event raises everyone's negativity at
                   the same moment, and bursty activity makes it look local.

These three are famously hard to separate, and they are hard here on purpose: a lagged
neighbour regression finds a positive coefficient under all three. The separating evidence
is tie-formation time, which the pack supplies and which a naive analysis never opens.

Synthetic. Separating the three demonstrates inference mechanics, not a finding about any
real reputation system.
"""

